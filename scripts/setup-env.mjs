// Runs before `npm run dev` / `npm run build`:
//   1. creates .env with a random AUTH_SECRET and the local SQLite URL if missing,
//   2. applies database migrations (prisma migrate deploy),
//   3. generates the Prisma client if it is missing.
// Existing values in .env are never overwritten.
import { spawnSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

import { ROOT } from "./python.mjs";

const envPath = path.join(ROOT, ".env");
const existing = fs.existsSync(envPath) ? fs.readFileSync(envPath, "utf8") : "";
const has = (key) => new RegExp(`^\\s*${key}\\s*=`, "m").test(existing);
const additions = [];
if (!has("DATABASE_URL")) additions.push('DATABASE_URL="file:../data/app.db"');
if (!has("AUTH_SECRET")) additions.push(`AUTH_SECRET="${crypto.randomBytes(32).toString("base64url")}"`);
if (!has("AUTH_URL")) additions.push('AUTH_URL="http://localhost:3000"');
if (additions.length) {
  const header = existing ? "\n" : "# Generated by scripts/setup-env.mjs. See .env.example for all options.\n";
  fs.writeFileSync(envPath, existing + header + additions.join("\n") + "\n");
  console.log(`[retrainwise] wrote ${additions.map((a) => a.split("=")[0]).join(", ")} to .env`);
}
fs.mkdirSync(path.join(ROOT, "data"), { recursive: true });

const npx = process.platform === "win32" ? "npx.cmd" : "npx";
function prisma(args) {
  const r = spawnSync(npx, ["prisma", ...args], { cwd: ROOT, stdio: "inherit", shell: process.platform === "win32" });
  if (r.status !== 0) {
    console.error(`[retrainwise] prisma ${args.join(" ")} failed`);
    process.exit(r.status ?? 1);
  }
}
if (!fs.existsSync(path.join(ROOT, "node_modules", ".prisma", "client", "index.js"))) prisma(["generate"]);
prisma(["migrate", "deploy"]);
